def generate_section_nav_scroll_js():
    """Return JS that defines setupSectionNavScroll(containerSelector, linkSelector, offsetPx) for smooth scroll to section anchors."""
    return """
    function setupSectionNavScroll(containerSelector, linkSelector, offsetPx) {
        const container = document.querySelector(containerSelector);
        if (!container) return;
        container.querySelectorAll(linkSelector).forEach(function(link) {
            link.addEventListener('click', function(e) {
                const id = this.getAttribute('href').substring(1);
                const target = document.getElementById(id);
                if (target) {
                    e.preventDefault();
                    const navHeight = container.offsetHeight;
                    const top = target.getBoundingClientRect().top + window.pageYOffset - navHeight - offsetPx;
                    window.scrollTo({ top: top, behavior: 'smooth' });
                }
            });
        });
    }
    """


def generate_common_js():
    """Generate common JavaScript functions"""
    return """
    // Fixed width per hour in pixels (7cm = ~265px at standard 96 DPI)
    const PIXELS_PER_HOUR = 265;

    // Row height reduced by 25% from original 37.5px
    const ROW_HEIGHT = 28; // 75% of original height
    const HEADER_HEIGHT = 22; // Reduced from 30px

    // Store all job rectangles for filtering
    const allJobRects = [];

    // Format duration in a human-readable way
    function formatDuration(seconds) {
        if (seconds === null || seconds === undefined) return 'N/A';

        if (seconds < 60) return `${Math.round(seconds)} seconds`;

        const minutes = Math.floor(seconds / 60);
        if (minutes < 60) return `${minutes} min ${Math.round(seconds % 60)} sec`;

        const hours = Math.floor(minutes / 60);
        return `${hours} hr ${minutes % 60} min`;
    }

    // Time scale function (using UTC time)
    function timeToPosition(timeStr, minTime) {
        const time = new Date(timeStr);
        const dayStart = new Date(minTime);

        // Calculate hours elapsed since the start of this day's timeline
        const hoursSinceStart = (time - dayStart) / (1000 * 3600);

        return hoursSinceStart * PIXELS_PER_HOUR;
    }
    """


def generate_timeline_js(date, date_data, runners, projects):
    """Generate JavaScript for a specific date's timeline"""
    runner_rows = date_data["runner_rows"]
    min_time = date_data["min_time"]

    # Calculate total height needed and prepare runner layout
    total_height = HEADER_HEIGHT
    runner_layout = []

    # Create a layout structure with runner information for the specified runners
    for runner in runners:
        rows = runner_rows.get(runner, [])
        row_count = max(1, len(rows))  # At least one row per runner

        runner_layout.append(
            {"runner": runner, "rowCount": row_count, "startRow": total_height, "rows": rows, "isEmpty": len(rows) == 0}
        )

        total_height += row_count * ROW_HEIGHT + HEADER_HEIGHT

    # Calculate chart width based on hours to display (always 24 hours)
    hours_to_display = 24
    chart_width = hours_to_display * PIXELS_PER_HOUR

    # HTML for the timeline container - removed project toggles from here
