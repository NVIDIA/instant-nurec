def collect_statistics_data(processed_data):
    """Collect statistics data for graphs"""
    dates = processed_data["dates"]
    processed_dates = processed_data["processed_dates"]
    projects = processed_data["projects"]

    # Data structures for statistics
    job_durations_by_date = defaultdict(lambda: defaultdict(list))
    jobs_count_by_date = defaultdict(int)
    jobs_count_by_project_date = defaultdict(lambda: defaultdict(int))

    # Add new counter for pipelines per date
    pipelines_count_by_date = defaultdict(int)
    unique_pipelines_by_date = defaultdict(set)  # Track unique pipelines per date

    # Add new counter for failed jobs on main branch
    failed_main_jobs_by_date = defaultdict(int)

    # Add new counter for maglev_launch_ndas_workflow* jobs by date, classification, and job name
    # Structure: [date][classification][job_name] = count
    maglev_jobs_by_date = defaultdict(lambda: defaultdict(lambda: defaultdict(int)))

    # Add new counters for classified pipelines and jobs per date
    pipelines_by_classification_date = defaultdict(lambda: defaultdict(int))  # [date][classification] = count
    jobs_by_classification_date = defaultdict(lambda: defaultdict(int))  # [date][classification] = count
    unique_pipelines_by_classification_date = defaultdict(
        lambda: defaultdict(set)
    )  # [date][classification] = set of pipeline_ids

    # Track which jobs have been run on the main branch
    main_branch_jobs = set()

    # Get current date for past week calculation
    current_date = datetime.datetime.now().date()
    one_week_ago = current_date - datetime.timedelta(days=7)

    # First pass: collect all jobs and group by pipeline to find earliest created_at dates
    pipeline_info = {}  # pipeline_id -> {earliest_date, classification, identifier}
    all_jobs = []  # Store all jobs for second pass

    # Process each date to collect all jobs
    for date in dates:
        date_obj = datetime.date.fromisoformat(date)
        date_data = processed_dates[date]
        runner_rows = date_data["runner_rows"]

        # Process all jobs (NRS only for statistics)
        for runner, rows in runner_rows.items():
            for row in rows:
                for job in row:
                    if job.get("is_non_nrs_project"):
                        continue
                    all_jobs.append((date, job))

                    pipeline_id = job["pipeline_id"]
                    job_created_at = job["created_at"]

                    # Convert created_at timestamp to date for daily grouping (using UTC)
                    pipeline_date = (
                        datetime.datetime.fromisoformat(job_created_at.replace("Z", "+00:00"))
                        .astimezone(datetime.timezone.utc)
                        .date()
                        .isoformat()
                    )

                    ref_classification = job.get("ref_classification", "pre-merge")

                    # Track earliest date for this pipeline
                    if pipeline_id not in pipeline_info:
                        pipeline_info[pipeline_id] = {
                            "earliest_date": pipeline_date,
                            "classification": ref_classification,
                            "identifier": pipeline_id,
                        }
                    else:
                        # Update if we found an earlier date
                        if pipeline_date < pipeline_info[pipeline_id]["earliest_date"]:
                            pipeline_info[pipeline_id]["earliest_date"] = pipeline_date

    # Second pass: process jobs using pipeline dates
    for date, job in all_jobs:
        # Increment job count for this date (jobs still use their started_at date)
        jobs_count_by_date[date] += 1

        # Increment job count for this project and date
        project = job.get("project", "unknown")
        jobs_count_by_project_date[project][date] += 1

        # Get pipeline identifier
        pipeline_id = job["pipeline_id"]

        # Get pipeline date and classification from our pre-computed info
        pipeline_date = pipeline_info[pipeline_id]["earliest_date"]
        pipeline_classification = pipeline_info[pipeline_id]["classification"]

        # Track pipelines by their date
        unique_pipelines_by_date[pipeline_date].add(pipeline_id)

        # Track classified pipeline counts
        unique_pipelines_by_classification_date[pipeline_date][pipeline_classification].add(pipeline_id)

        job_name = job["name"]
        is_main = job.get("is_main", False)
        ref_classification = job.get("ref_classification", "pre-merge")

        # Track classified job counts (jobs still use their started_at date)
        jobs_by_classification_date[date][ref_classification] += 1

        # Count failed jobs on main branch
        if is_main and job["status"] == "failed":
            failed_main_jobs_by_date[date] += 1

        # Count maglev_launch_ndas_workflow* jobs by classification and job name
        if job_name.startswith("maglev_launch_ndas_workflow"):
            maglev_jobs_by_date[date][ref_classification][job_name] += 1

        # Create a project-specific job identifier
        project_job = f"{project} - {job_name}"

        # Track jobs that run on main branch
        if is_main:
            main_branch_jobs.add(project_job)

        # Collect job durations by date for successful jobs only
        # (collect for all branches, not just main)
        if job.get("duration") is not None and job["status"] == "success":
            job_durations_by_date[project_job][date].append(job["duration"])

    # Convert unique pipelines per date to counts
    for date, pipeline_set in unique_pipelines_by_date.items():
        pipelines_count_by_date[date] = len(pipeline_set)

    # Convert classified pipeline sets to counts
    for date, classification_dict in unique_pipelines_by_classification_date.items():
        for classification, pipeline_set in classification_dict.items():
            pipelines_by_classification_date[date][classification] = len(pipeline_set)

    # Average job durations: only NRS jobs that have run on main branch at least once
    avg_job_durations_by_date = {}
    for project_job, date_durations in job_durations_by_date.items():
        if project_job not in main_branch_jobs:
            continue
        avg_job_durations_by_date[project_job] = {}
        for date, durations in date_durations.items():
            if durations:
                avg_job_durations_by_date[project_job][date] = sum(durations) / len(durations)

    return {
        "avg_job_durations_by_date": avg_job_durations_by_date,
        "jobs_count_by_date": jobs_count_by_date,
        "jobs_count_by_project_date": jobs_count_by_project_date,
        "pipelines_count_by_date": pipelines_count_by_date,  # Add pipeline count data
        "main_branch_jobs": main_branch_jobs,
        "projects": projects,
        "failed_main_jobs_by_date": failed_main_jobs_by_date,  # Add the new data
        "maglev_jobs_by_date": maglev_jobs_by_date,  # Add maglev workflow jobs data
        "pipelines_by_classification_date": pipelines_by_classification_date,  # Add classified pipeline data
        "jobs_by_classification_date": jobs_by_classification_date,  # Add classified job data
    }


