def _short_image_label(full_name):
    """Use last segment (repo:tag) for display."""
    if "/" in full_name:
        return full_name.rsplit("/", 1)[-1]
    return full_name


def generate_container_image_sizes_html(data, output_folder):
    """Generate container_image_sizes.html with comparison chart and size history (one point per day)."""
    images = data.get("images") or {}
    history = data.get("history") or []
    history = sorted(history, key=lambda h: h.get("date", ""))

    # Comparison: bar chart from latest images (bytes -> GiB)
    comparison_labels = [_short_image_label(k) for k in sorted(images.keys())]
    comparison_values = [round((images[k] or 0) / (1024**3), 2) for k in sorted(images.keys())]

    # History: one chart per image. Build sorted dates and per-image value list (GiB).
    all_dates = sorted(set(h.get("date") for h in history if h.get("date")))
    all_image_names_set = set()
    for h in history:
        all_image_names_set.update((h.get("images") or {}).keys())
    all_image_names = sorted(all_image_names_set)
    date_to_idx = {d: i for i, d in enumerate(all_dates)}
    history_charts = []
    for img in all_image_names:
        vals = [None] * len(all_dates)
        for h in history:
            day = h.get("date")
            if day not in date_to_idx:
                continue
            imgs = h.get("images") or {}
            if img in imgs and imgs[img]:
                vals[date_to_idx[day]] = round(imgs[img] / (1024**3), 2)
        safe_id = html.escape(img.replace("/", "_").replace(":", "_"), quote=True)
        history_charts.append({"id": safe_id, "shortLabel": _short_image_label(img), "values": vals})

