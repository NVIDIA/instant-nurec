def filter_jobs_for_display(jobs_data):
    """Filter job list for visualization.

    NRS group jobs are included as-is. Non-NRS jobs (see EXTRA_PROJECTS_OWN_RUNNER_ONLY)
    are included in dashboard views only when they ran on runners owned by NRS (description starting with
    OWN_RUNNER_DESCRIPTION_PREFIX).
    """
    filtered = []
    for job in jobs_data:
        project_path = (job.get("project_name") or "").strip()
        if project_path in EXTRA_PROJECTS_OWN_RUNNER_ONLY:
            runner_desc = job.get("runner_description") or ""
            if not runner_desc.startswith(OWN_RUNNER_DESCRIPTION_PREFIX):
                continue
        filtered.append(job)
    return filtered


def load_test_runtimes(output_folder):
    """Load test runtimes JSON (ci_test_runtimes.json) if present. Returns None if file missing or invalid."""
    path = os.path.join(output_folder, "ci_test_runtimes.json")
    if not os.path.exists(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        if not isinstance(data.get("runs"), list):
            return None
        return data
    except (json.JSONDecodeError, OSError):
        return None


def load_container_image_sizes(output_folder):
    """Load container_image_sizes.json (array of {date, images}). Returns None if file missing or invalid."""
    path = os.path.join(output_folder, "container_image_sizes.json")
    if not os.path.exists(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        if not isinstance(data, list):
            return None
        history = data
        images = history[-1].get("images") or {} if history else {}
        return {"images": images, "history": history}
    except (json.JSONDecodeError, OSError):
        return None


def parse_job_timestamp(timestamp_str):
    """Parse ISO timestamp and ensure UTC timezone"""
    if not timestamp_str:
        return None
    return datetime.datetime.fromisoformat(timestamp_str.replace("Z", "+00:00"))


def get_job_color(status):
    """Determine job color based on status"""
    if status == "success":
        return "#28a745"  # green
    elif status == "failed":
        return "#dc3545"  # red
    else:  # canceled or other
        return "#6c757d"  # grey


def classify_ref(ref):
    """Classify a git ref into pipeline/job categories

    Args:
        ref: Git reference string

    Returns:
        str: One of 'post-merge', 'merge-train', 'pre-merge'
    """
    if not ref:
        return "pre-merge"

    ref = ref.strip()

    # Post-merge: main branch and release branches
    if ref == "main" or ref == "master" or ref.startswith("release/"):
        return "post-merge"

    # Merge train: specific merge request train pattern
    if ref.startswith("refs/merge-requests/") and ref.endswith("/train"):
        return "merge-train"

    # Everything else is pre-merge (feature branches, other MRs, etc.)
    return "pre-merge"


def process_job(job):
    """Process a single job and return structured data"""
    # Skip jobs without started_at or finished_at
    if not job.get("started_at") or not job.get("finished_at"):
        return None

    # Parse dates (ensure UTC)
    created_at = parse_job_timestamp(job["created_at"])
    started_at = parse_job_timestamp(job["started_at"])
    finished_at = parse_job_timestamp(job["finished_at"])

    # Get date in UTC for grouping
    started_date_utc = started_at.astimezone(datetime.timezone.utc).date().isoformat()

    # Get runner name or ID, ensuring it's not None and distinguishing between unknown runners
    runner_id = job.get("runner_id")
    runner_description = job.get("runner_description")

    if runner_description:
        runner = runner_description
    elif runner_id is not None:
        runner = f"unknown-{runner_id}"
    else:
        runner = "unknown-no-id"

    # Get ref name (default to 'unknown' if not available)
    ref = job.get("ref", "unknown")

    # Extract project name from project_name field (without path)
    project_name = "unknown"
    if job.get("project_name"):
        # Get the last part of the path (after the last /)
        project_name = job["project_name"].split("/")[-1]

    # Create a combined job name with project prefix
    combined_name = f"{project_name} - {job['name']}"

    # Classify the ref
    ref_classification = classify_ref(ref)

    project_full = job.get("project_name", "unknown")
    is_non_nrs_project = project_full.strip() in EXTRA_PROJECTS_OWN_RUNNER_ONLY

    return {
        "id": job["id"],
        "pipeline_id": job["pipeline_id"],
        "name": job["name"],
        "combined_name": combined_name,
        "project": project_name,
        "project_full": project_full,
        "user": job.get("user", "unknown"),
        "status": job["status"],
        "created_at": created_at.isoformat(),  # created_at field used for pipeline dating
        "started_at": started_at.isoformat(),
        "finished_at": finished_at.isoformat(),
        "duration": job.get("duration", 0),
        "queued_duration": job.get("queued_duration", 0),
        "color": get_job_color(job["status"]),
        "web_url": job.get("web_url", "#"),
        "runner": runner,
        "ref": ref,
        "ref_classification": ref_classification,
        "is_main": ref == "main" or ref == "master",  # Flag for main branch
        "date": started_date_utc,
        "commit_title": job.get("commit_title", "N/A"),
        "is_non_nrs_project": is_non_nrs_project,
    }


def process_job_data(jobs_data):
    """Process job data for visualization"""
    # Group jobs by date
    jobs_by_date = defaultdict(list)

    # Collect all unique runners and projects
    all_runners = set()
    all_projects = set()

    for job in jobs_data:
        # Process the job using the common process_job function
        processed_job = process_job(job)
        if processed_job:
            # Add to set of all projects
            all_projects.add(processed_job["project"])

            # Add to set of all runners
            all_runners.add(processed_job["runner"])

            # Add job to the appropriate date list (using UTC date)
            jobs_by_date[processed_job["date"]].append(processed_job)

            # If the job spans midnight UTC, split it: clamp the start-day entry at
            # midnight and add a continuation entry for the next day.  We only handle
            # a single midnight crossing (CI jobs don't realistically run 24+ hours).
            started_at_dt = datetime.datetime.fromisoformat(processed_job["started_at"])
            finished_at_dt = datetime.datetime.fromisoformat(processed_job["finished_at"])
            finished_date = finished_at_dt.astimezone(datetime.timezone.utc).date()
            started_date = started_at_dt.astimezone(datetime.timezone.utc).date()
            if finished_date > started_date:
                midnight = datetime.datetime.combine(finished_date, datetime.time.min, tzinfo=datetime.timezone.utc)
                # Continuation entry for the next day (original finished_at preserved)
                next_day_job = processed_job.copy()
                next_day_job["date"] = finished_date.isoformat()
                next_day_job["started_at"] = midnight.isoformat()
                jobs_by_date[finished_date.isoformat()].append(next_day_job)
                # Clamp start-day entry at midnight so it renders to the right edge
                processed_job["finished_at"] = midnight.isoformat()

    # Sort dates, runners, and projects
    sorted_dates = sorted(list(jobs_by_date.keys()))
    sorted_runners = sorted(list(all_runners))
    sorted_projects = sorted(list(all_projects))

    # For each date, organize jobs by runner and assign rows to jobs to avoid overlap
    processed_dates = {}

    for date in sorted_dates:
        jobs = jobs_by_date[date]

        # Group jobs by runner
        runner_jobs = defaultdict(list)
        for job in jobs:
            runner_jobs[job["runner"]].append(job)

        # For each runner, assign rows to jobs to avoid overlap
        runner_rows = {}

        for runner in sorted_runners:
            jobs = runner_jobs.get(runner, [])

            # If no jobs for this runner on this day, add an empty entry
            if not jobs:
                runner_rows[runner] = []
                continue

            # Sort jobs by start time
            jobs.sort(key=lambda j: j["started_at"])

            # Assign rows to avoid overlap
            rows = []
            for job in jobs:
                # Find a row where this job doesn't overlap with existing jobs
                assigned = False
                for row_idx, row in enumerate(rows):
                    # Check if job overlaps with any job in this row
                    overlaps = False
                    for existing_job in row:
                        if (
                            job["started_at"] < existing_job["finished_at"]
                            and job["finished_at"] > existing_job["started_at"]
                        ):
                            overlaps = True
                            break

                    if not overlaps:
                        # Add job to this row
                        row.append(job)
                        job["row"] = row_idx
                        assigned = True
                        break

                if not assigned:
                    # Create a new row for this job
                    job["row"] = len(rows)
                    rows.append([job])

            runner_rows[runner] = rows

        # Set fixed time range for the day (00:00 to 23:59 UTC)
        day_start = datetime.datetime.fromisoformat(date + "T00:00:00+00:00")
        day_end = datetime.datetime.fromisoformat(date + "T23:59:59+00:00")

        # Store processed data for this date
        processed_dates[date] = {
            "runner_rows": runner_rows,
            "min_time": day_start.isoformat(),
            "max_time": day_end.isoformat(),
            "hours_to_display": 24,  # Always display 24 hours
            "min_hour": day_start.isoformat(),
        }

    # Group dates by month
    dates_by_month = defaultdict(list)
    for date in sorted_dates:
        year_month = date[:7]  # Extract YYYY-MM
        dates_by_month[year_month].append(date)

    return {
        "dates": sorted_dates,
        "runners": sorted_runners,
        "projects": sorted_projects,
        "processed_dates": processed_dates,
        "dates_by_month": {month: sorted(dates) for month, dates in dates_by_month.items()},
    }


