def generate_html(processed_data, output_folder, input_filename):
    """Generate HTML visualizations in the output folder"""
    dates = processed_data["dates"]
    runners = processed_data["runners"]
    processed_dates = processed_data["processed_dates"]
    dates_by_month = processed_data["dates_by_month"]
    projects = processed_data["projects"]

    # Create output folder if it doesn't exist
    os.makedirs(output_folder, exist_ok=True)

    # Load test runtimes and container image sizes for index links and page generation
    runtimes_data = load_test_runtimes(output_folder)
    container_image_sizes_data = load_container_image_sizes(output_folder)

    # Generate index.html
    index_path = generate_index_html(
        processed_data,
        output_folder,
        input_filename,
        test_runtimes_available=runtimes_data is not None,
        container_image_sizes_available=container_image_sizes_data is not None,
    )

    # Generate monthly HTML files
    for month, month_dates in dates_by_month.items():
        generate_month_html(month, month_dates, processed_dates, runners, projects, output_folder)

    # Generate statistics page
    stats_data = collect_statistics_data(processed_data)
    stats_path = generate_statistics_html(stats_data, output_folder)

    # Generate capacity analysis page
    try:
        from ci_capacity import generate_capacity_page

        # Extract job data from processed_data for capacity analysis
        # Pass the processed job data directly - ci_capacity.py now supports this format
        job_data = []
        for date, date_data in processed_dates.items():
            for runner, rows in date_data["runner_rows"].items():
                for row in rows:
                    for job in row:
                        job_data.append(job)

        # Generate capacity analysis page
        capacity_path = generate_capacity_page(job_data, output_folder)

        print(f"Generated capacity analysis file: {capacity_path}")
    except ImportError as e:
        print(f"Warning: Could not import capacity analysis modules: {e}")
        print("Capacity analysis features will not be available")
    except Exception as e:
        print(f"Warning: Error generating capacity analysis: {e}")
        print("Capacity analysis features will not be available")

    # Generate test runtimes page if test runtimes data is available
    if runtimes_data:
        test_runtimes_path = generate_test_runtimes_html(runtimes_data, output_folder)
        if test_runtimes_path:
            print(f"Generated test runtimes file: {test_runtimes_path}")
    else:
        test_runtimes_path = None

    # Generate container image sizes page if data is available
    if container_image_sizes_data:
        container_image_sizes_path = generate_container_image_sizes_html(container_image_sizes_data, output_folder)
        if container_image_sizes_path:
            print(f"Generated container image sizes file: {container_image_sizes_path}")

    print(f"Generated index file: {index_path}")
    print(f"Generated {len(dates_by_month)} monthly visualization files")
    print(f"Generated statistics file: {stats_path}")


