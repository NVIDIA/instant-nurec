def calculate_month_stats(month_dates, processed_dates):
    """Calculate job statistics for a month"""
    total_jobs = 0
    success_count = 0
    failed_count = 0
    other_count = 0

    # Maglev job counts by type
    maglev_base_count = 0
    maglev_nightly_count = 0
    maglev_weekly_count = 0

    # Track unique pipelines for this month
    unique_pipelines = set()

    for date in month_dates:
        date_data = processed_dates[date]
        runner_rows = date_data["runner_rows"]

        for runner, rows in runner_rows.items():
            for row in rows:
                for job in row:
                    if job.get("is_non_nrs_project"):
                        continue
                    total_jobs += 1
                    if job["status"] == "success":
                        success_count += 1
                    elif job["status"] == "failed":
                        failed_count += 1
                    else:
                        other_count += 1

                    # Count Maglev jobs by type
                    job_name = job.get("name", "")
                    if job_name.startswith("maglev_launch_ndas_workflow"):
                        if "nightly" in job_name:
                            maglev_nightly_count += 1
                        elif "weekly" in job_name:
                            maglev_weekly_count += 1
                        else:
                            maglev_base_count += 1

                    # Track unique pipelines (same logic as in collect_statistics_data)
                    unique_pipelines.add(job["pipeline_id"])

    return {
        "total": total_jobs,
        "success": success_count,
        "failed": failed_count,
        "other": other_count,
        "days": len(month_dates),
        "pipelines": len(unique_pipelines),
        "maglev_base": maglev_base_count,
        "maglev_nightly": maglev_nightly_count,
        "maglev_weekly": maglev_weekly_count,
    }


def get_month_name(year_month):
    """Get the full month name from a YYYY-MM string"""
    year, month = map(int, year_month.split("-"))
    return f"{calendar.month_name[month]} {year}"


