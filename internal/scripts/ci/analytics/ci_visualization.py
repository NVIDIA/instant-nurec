def _build_test_runtimes_page_data(runtimes_data):
    """Build structures for the test runtimes page: per-target history and latest-run pareto."""
    runs = runtimes_data.get("runs") or []
    if not runs:
        return None
    runs = sorted(runs, key=lambda r: (r.get("date", ""), r.get("pipeline_id", 0)))
    latest = runs[-1]
    latest_targets = {t["target"] for t in latest.get("tests") or []}

    # Per-target history: list of (date, runtime_seconds, timeout_seconds) and in_latest flag
    target_history = defaultdict(list)
    for run in runs:
        date = run.get("date", "")
        for t in run.get("tests") or []:
            target = t.get("target", "")
            if not target:
                continue
            target_history[target].append(
                {
                    "date": date,
                    "runtime_seconds": t.get("runtime_seconds") or 0,
                    "timeout_seconds": t.get("timeout_seconds"),
                }
            )
    target_list = []
    for target, points in sorted(target_history.items()):
        points.sort(key=lambda p: p["date"])
        target_list.append(
            {
                "target": target,
                "in_latest": target in latest_targets,
                "points": points,
            }
        )

    # Pareto: latest run's tests sorted by runtime descending
    pareto = []
    for t in latest.get("tests") or []:
        target = t.get("target", "")
        if target:
            pareto.append(
                {
                    "target": target,
                    "runtime_seconds": t.get("runtime_seconds") or 0,
                }
            )
    pareto.sort(key=lambda x: -x["runtime_seconds"])

    # Split into default tests and SQA lite (//internal/sqa:sqa_test*)
    _SQA_LITE_PREFIX = "//internal/sqa:sqa_test"
    pareto_default = [x for x in pareto if not (x.get("target") or "").startswith(_SQA_LITE_PREFIX)]
    pareto_sqa_lite = [x for x in pareto if (x.get("target") or "").startswith(_SQA_LITE_PREFIX)]

    all_dates = sorted(set(r.get("date") for r in runs if r.get("date")))

    return {
        "targets": target_list,
        "pareto_default": pareto_default,
        "pareto_sqa_lite": pareto_sqa_lite,
        "latest_date": latest.get("date", ""),
        "latest_pipeline_id": latest.get("pipeline_id"),
        "all_dates": all_dates,
    }


